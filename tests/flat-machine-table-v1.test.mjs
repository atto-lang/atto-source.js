import test from 'node:test';
import assert from 'node:assert/strict';
import { verifyFlatMachineTable as verify } from '../src/flat-machine-table-v1.mjs';
const e = (event, target) => ({event, target});
const n = (name, terminal, ...edges) => ({name, terminal, edges});
const graph = () => [n('Alpha', true), n('Zed', false, e('AlphaEvent', 0), e('Zulu', 1))];
const bad = (name, run) => test(name, () => assert.throws(run, /E_MACHINE_TABLE/));
const id = (prefix, i) => `${prefix}${1000 + i}`;
test('initial', () => assert.equal(verify(1, graph()).initial, 1));
test('node order', () => assert.deepEqual(verify(1, graph()).names, ['Alpha', 'Zed']));
test('event slots', () => assert.deepEqual(verify(1, graph()).events, ['AlphaEvent', 'Zulu']));
test('transition', () => assert.equal(verify(1, graph()).successor(1, 0), 0));
test('self transition', () => assert.equal(verify(1, graph()).successor(1, 1), 1));
test('terminal no edge', () => assert.equal(verify(1, graph()).successor(0, 0), null));
bad('invalid node', () => verify(1, graph()).successor(2, 0));
bad('invalid event slot', () => verify(1, graph()).successor(1, 2));
bad('invalid initial', () => verify(2, graph()));
bad('empty graph', () => verify(0, []));
bad('unsorted nodes', () => verify(1, graph().reverse()));
bad('terminal edge', () => verify(1, [n('Alpha', true, e('X', 1)), graph()[1]]));
bad('unsorted events', () => verify(1, [graph()[0], n('Zed', false, e('Zulu', 1), e('AlphaEvent', 0))]));
bad('invalid target', () => verify(1, [graph()[0], n('Zed', false, e('AlphaEvent', 9))]));
bad('unreachable', () => verify(1, [graph()[0], n('Zed', false, e('Zulu', 1))]));
bad('duplicate event', () => verify(0, [n('A', false, e('E', 0), e('E', 0))]));
bad('empty name', () => verify(0, [n('', true)]));
bad('overlong name', () => verify(0, [n('a'.repeat(1025), true)]));
bad('non-ASCII name', () => verify(0, [n('é', true)]));
const edges = (size) => Array.from({length: size}, (_, i) => e(id('E', i), 0));
test('exact edge bound', () => assert.equal(verify(0, [n('N', false, ...edges(256))]).events.length, 256));
bad('edge overflow', () => verify(0, [n('N', false, ...edges(257))]));
const nodes = (size) => Array.from({length: size}, (_, i) => n(id('N', i), i === size-1, ...(i === size-1 ? [] : [e('Next', i+1)])));
test('exact node bound', () => assert.equal(verify(0, nodes(256)).names.length, 256));
bad('node overflow', () => verify(0, nodes(257)));
const cycle = () => verify(0, [n('Idle', false, e('Start', 1)), n('Running', false, e('Stop', 0))]);
test('cycle forward', () => assert.equal(cycle().successor(0, 0), 1));
test('cycle back', () => assert.equal(cycle().successor(1, 1), 0));
test('missing edge', () => assert.equal(cycle().successor(1, 0), null));
bad('fractional target', () => verify(0, [n('A', false, e('E', 0.5))]));
bad('NaN slot', () => verify(1, graph()).successor(1, NaN));
bad('trailing newline name', () => verify(0, [n('A\n', true)]));
test('no aliases to source graph', () => {
  const g = graph(), table = verify(1, g);
  g[1].edges[0].target = 1;
  g[0].name = 'Other';
  assert.equal(table.successor(1, 0), 0);
  assert.deepEqual(table.names, ['Alpha', 'Zed']);
  assert.throws(() => { table.names[0] = 'Other'; }, TypeError);
});
