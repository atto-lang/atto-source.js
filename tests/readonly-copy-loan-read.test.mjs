import test from 'node:test';
import assert from 'node:assert/strict';
import { ReadonlyCopyDomain } from '../src/readonly-copy-domain.mjs';
const make = (d, value) => {
  const o = d.create({dynamic:true});
  d.initialize(o, 'n', value);
  d.finish(o);
  return o;
};
const deny = (code, fn) => assert.throws(fn, {code});
test('loan reads remain valid across detachment and owner retirement', () => {
  const d = new ReadonlyCopyDomain();
  const a = make(d, 1), ar = d.identity(a);
  const child = make(d, 20), cr = d.identity(child);
  const leaf = make(d, 22), lr = d.identity(leaf);
  d.moveInto(child, cr, 'leaf', leaf);
  d.moveInto(a, ar, 'child', child);
  const b = d.copy(a), br = d.identity(b);
  const loan = d.readLoan(b, cr);
  d.remove(b, br, 'child');
  d.drop(b);
  deny('E_COPY_LOAN', () => d.setScalar(a, lr, 'n', 99));
  d.remove(a, ar, 'child');
  d.drop(a);
  assert.equal(d.readBorrowed(loan, cr, 'leaf'), lr);
  assert.equal(d.readBorrowed(loan, cr, 'n') + d.readBorrowed(loan, lr, 'n'), 42);
  d.release(loan);
  deny('E_COPY_STALE', () => d.readBorrowed(loan, lr, 'n'));
});
test('loan access is scoped and never grants write or owner authority', () => {
  const d = new ReadonlyCopyDomain(), a = make(d, 1), ar = d.identity(a);
  const c = make(d, 20), cr = d.identity(c);
  const other = make(d, 22), or = d.identity(other);
  d.moveInto(a, ar, 'child', c);
  const l1 = d.readLoan(a, cr), l2 = d.readLoan(a, cr);
  for (const id of [ar, or, Object.freeze({})]) deny('E_COPY_DOMAIN', () => d.readBorrowed(l1, id, 'n'));
  deny('E_COPY_STALE', () => d.readBorrowed(a, cr, 'n'));
  deny('E_COPY_STALE', () => d.setScalar(l1, cr, 'n', 99));
  deny('E_COPY_STALE', () => d.copy(l1));
  const foreign = new ReadonlyCopyDomain(), f = make(foreign, 1), fr = foreign.identity(f);
  const fl = foreign.readLoan(f, fr);
  deny('E_COPY_STALE', () => d.readBorrowed(fl, cr, 'n'));
  deny('E_COPY_DOMAIN', () => d.readBorrowed(l1, fr, 'n'));
  d.release(l1);
  deny('E_COPY_STALE', () => d.readBorrowed(l1, cr, 'n'));
  assert.equal(d.readBorrowed(l2, cr, 'n'), 20);
  deny('E_COPY_LOAN', () => d.setScalar(a, cr, 'n', 99));
  d.release(l2);
  d.setScalar(a, cr, 'n', 42);
  assert.equal(d.read(a, cr, 'n'), 42);
});
